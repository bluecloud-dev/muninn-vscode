// Generates docs/ROUNDTRIP_REPORT.md and tests/unit/round-trip/KNOWN_DEVIATIONS.md from
// the round-trip corpus, and fails (exit 1) when deviations.json no longer matches
// observed behavior. Run via: npm run test:roundtrip
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const corpusPath = path.join(repoRoot, 'out', 'tests', 'unit', 'round-trip', 'corpus.js');
if (!fs.existsSync(corpusPath)) {
  throw new Error('Compiled round-trip corpus not found. Run npm run compile first.');
}

const corpus = require(corpusPath);

const outcomes = corpus.evaluateCorpus();
const records = corpus.loadDeviationRecords();
const recordsByFixture = new Map(records.map((record) => [record.fixture, record]));
const outcomeNames = new Set(outcomes.map((outcome) => outcome.fixtureName));

const problems = [];
for (const outcome of outcomes) {
  const record = recordsByFixture.get(outcome.fixtureName);
  if (!record) {
    if (!outcome.matches) {
      problems.push(
        `${outcome.fixtureName} fails round-trip without a deviations.json entry:\n` +
          corpus.formatMismatch(outcome.input, outcome.output),
      );
    }
    continue;
  }
  if (outcome.matches) {
    problems.push(
      `${outcome.fixtureName} now round-trips byte-identically — remove or re-classify its deviations.json entry`,
    );
  } else if (record.kind === 'final-newline-only' && !outcome.tailNewlineOnly) {
    problems.push(
      `${outcome.fixtureName} diverges beyond the trailing newline but is documented as final-newline-only`,
    );
  } else if (record.kind === 'construct' && outcome.tailNewlineOnly) {
    problems.push(
      `${outcome.fixtureName} now fails only by the trailing newline but is documented as a construct deviation`,
    );
  }
}
for (const record of records) {
  if (!outcomeNames.has(record.fixture)) {
    problems.push(`deviations.json references unknown fixture ${record.fixture}`);
  }
}
if (problems.length > 0) {
  console.error('Round-trip taxonomy is out of date:\n');
  for (const problem of problems) {
    console.error(`- ${problem}\n`);
  }
  process.exit(1);
}

const byteIdentical = outcomes.filter((outcome) => outcome.matches);
const tailOnly = outcomes.filter((outcome) => outcome.tailNewlineOnly);
const constructDeviations = outcomes.filter(
  (outcome) => !outcome.matches && !outcome.tailNewlineOnly,
);
const constructPreserved = byteIdentical.length + tailOnly.length;

const categories = new Map();
for (const outcome of outcomes) {
  const row = categories.get(outcome.category) || {
    cases: 0,
    byteIdentical: 0,
    tailOnly: 0,
    construct: 0,
  };
  row.cases += 1;
  if (outcome.matches) {
    row.byteIdentical += 1;
  } else if (outcome.tailNewlineOnly) {
    row.tailOnly += 1;
  } else {
    row.construct += 1;
  }
  categories.set(outcome.category, row);
}

const sample = (text) => {
  if (/\r/.test(text)) {
    return [
      '(shown as a JS string literal because the sample contains CR bytes)',
      '',
      '```',
      JSON.stringify(text),
      '```',
    ].join('\n');
  }
  const body = text.endsWith('\n') ? text : `${text}\n`;
  return `\`\`\`\`markdown\n${body}\`\`\`\``;
};

const generatedNotice =
  '<!-- Generated by scripts/generate-roundtrip-report.js via `npm run test:roundtrip`. Do not edit by hand. -->';
const equation = '`serializeToHostMarkdown(parseHostMarkdown(input)) === input`';

const knownDeviations = [];
knownDeviations.push(
  '# Known round-trip deviations',
  '',
  generatedNotice,
  '',
  `The golden corpus (\`tests/unit/round-trip/\`) asserts ${equation} byte-for-byte,`,
  'including trailing whitespace and final-newline state. Fixtures that cannot satisfy',
  'that today are recorded here with their exact output and root cause — documented',
  'honestly, never silently normalized away (#245). The test suite additionally asserts',
  'that each deviation fails in exactly the way documented here, so an entry that drifts',
  '(or quietly starts passing) breaks CI.',
  '',
  'Output samples are verbatim. Independently of each listed cause, the pure webview',
  'serializer still drops the final newline (#282). The host save path reconciles that',
  'state in `DocumentSync.applyDocument()` so real files that already end in `\\n` keep',
  'their final newline, while files without one do not gain one.',
  '',
  `## Final-newline-only deviations (#282) — ${tailOnly.length} fixtures`,
  '',
  'These fixtures round-trip their construct byte-identically and differ only by the',
  'missing trailing newline in the pure codec — a serializer defect reconciled by the host',
  'save path:',
  '',
);
for (const outcome of tailOnly) {
  knownDeviations.push(`- \`${outcome.fixtureName}\``);
}
knownDeviations.push('', `## Construct deviations — ${constructDeviations.length} fixtures`, '');
for (const outcome of constructDeviations) {
  const record = recordsByFixture.get(outcome.fixtureName);
  knownDeviations.push(
    `### \`${outcome.fixtureName}\` (${record.issue})`,
    '',
    `**Root cause**: ${record.rootCause}.`,
    '',
  );
  if (outcome.synthesizedFrom) {
    knownDeviations.push(`**Synthesized case**: ${outcome.synthesizedFrom}.`, '');
  }
  knownDeviations.push(
    '**Input**:',
    '',
    sample(outcome.input),
    '',
    '**Output**:',
    '',
    sample(outcome.output),
    '',
  );
}

const report = [];
report.push(
  '# Round-trip conformance report',
  '',
  generatedNotice,
  '',
  `**Property under test**: ${equation} — byte equality, including trailing whitespace`,
  'and final-newline state. This is the exact pipeline the editor runs between the host',
  'document and the ProseMirror view (`src/webview/editor/markdown-codec.ts`).',
  '',
  `**Corpus**: ${outcomes.length} cases — ${outcomes.length - 4} stored fixtures plus 4`,
  'synthesized byte-fragile variants (CRLF, trailing space, two-space hard break, missing',
  'final newline) that editors would silently normalize if stored on disk. This is the',
  'hand-curated construct corpus from issue #245, not the full CommonMark 0.31.2 example',
  'suite (that larger corpus is spec requirement R-01 and tracked separately).',
  '',
  '## Results',
  '',
  '| Verdict | Cases |',
  '| --- | ---: |',
  `| Byte-identical | ${byteIdentical.length} |`,
  `| Final-newline-only deviation (single root cause, #282) | ${tailOnly.length} |`,
  `| Construct deviations | ${constructDeviations.length} |`,
  `| **Total** | **${outcomes.length}** |`,
  '',
  '**Reading the numbers honestly**: the markdown construct survives byte-identically in',
  `${constructPreserved} of ${outcomes.length} cases; the missing trailing newline (#282) is a single`,
  'pure-serializer defect that still blocks every stored fixture from a strict codec pass,',
  'but the host save path now preserves the existing final-newline state for real files.',
  'Construct deviations remain; each has a tracking issue in the deviation index below.',
  'Until #283/#284 are fixed, hard-wrapped paragraphs unfold and dash bullets,',
  'underscore emphasis, and setext headings are rewritten to canonical forms.',
  '',
  '## Per-category breakdown',
  '',
  '| Category | Cases | Byte-identical | Final-newline-only | Construct deviations |',
  '| --- | ---: | ---: | ---: | ---: |',
);
for (const [category, row] of [...categories.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  report.push(
    `| ${category} | ${row.cases} | ${row.byteIdentical} | ${row.tailOnly} | ${row.construct} |`,
  );
}
report.push(
  '',
  '## Deviation index',
  '',
  '| Fixture | Kind | Root cause | Issue |',
  '| --- | --- | --- | --- |',
);
for (const record of records) {
  report.push(`| \`${record.fixture}\` | ${record.kind} | ${record.rootCause} | ${record.issue} |`);
}
report.push(
  '',
  'Full input/output samples: `tests/unit/round-trip/KNOWN_DEVIATIONS.md`.',
  'Run locally: `npm run test:roundtrip`.',
  '',
);

fs.writeFileSync(
  path.join(repoRoot, 'tests', 'unit', 'round-trip', 'KNOWN_DEVIATIONS.md'),
  `${knownDeviations.join('\n')}\n`.replace(/\n{3,}$/, '\n'),
);
fs.writeFileSync(path.join(repoRoot, 'docs', 'ROUNDTRIP_REPORT.md'), report.join('\n'));

console.log(
  `round-trip report: ${byteIdentical.length} byte-identical, ${tailOnly.length} final-newline-only, ` +
    `${constructDeviations.length} construct deviations (total ${outcomes.length})`,
);
console.log('wrote docs/ROUNDTRIP_REPORT.md and tests/unit/round-trip/KNOWN_DEVIATIONS.md');
